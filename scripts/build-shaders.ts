import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const shadersDir = path.resolve(__dirname, "../src/lib/shaders");

const gbufferWgsl = fs.readFileSync(path.join(shadersDir, "gbuffer.wgsl"), "utf8").trim();
const lineMarcherWgsl = fs.readFileSync(path.join(shadersDir, "line-marcher.wgsl"), "utf8").trim();
const previewWgsl = fs.readFileSync(path.join(shadersDir, "preview.wgsl"), "utf8").trim();

const targetFile = path.join(shadersDir, "index.ts");

function escapeForTemplateString(str: string): string {
  return str.replace(/`/g, "\\`").replace(/\${/g, "\\${");
}

const generatedContent = `// Auto-generated by scripts/build-shaders.ts — DO NOT EDIT DIRECTLY.
// Edit the corresponding .wgsl files in src/lib/shaders/ and run: npm run build:shaders
import { prepareShader } from "@vgpu/wgsl/prepare";

export const GBUFFER_WGSL = /* wgsl */ \`
${escapeForTemplateString(gbufferWgsl)}
\`;

export const LINE_MARCHER_WGSL = /* wgsl */ \`
${escapeForTemplateString(lineMarcherWgsl)}
\`;

export const PREVIEW_WGSL = /* wgsl */ \`
${escapeForTemplateString(previewWgsl)}
\`;

export const GBUFFER_SHADER = prepareShader(GBUFFER_WGSL);
export const LINE_MARCHER_SHADER = prepareShader(LINE_MARCHER_WGSL);
export const PREVIEW_SHADER = prepareShader(PREVIEW_WGSL);
`;

fs.writeFileSync(targetFile, generatedContent, "utf8");
console.log("Successfully generated src/lib/shaders/index.ts from .wgsl source files.");
